"""Render only explicit evidence placeholders, and reject untraceable numeric prose."""

import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any

from nous.research.design import REGISTRATION, ROOT, digest
from nous.research.report import markdown

PLACEHOLDER = re.compile(r"\{\{(table|fig):([a-z0-9_]+)\}\}")


def validate_source(source: str) -> None:
    text = PLACEHOLDER.sub("", source)

    def mathematical(match: re.Match[str]) -> str:
        expression = match.group()
        # Symbolic formula constants are allowed; measured decimals and scalar claims are not.
        if expression.startswith("$$"):
            numbers = re.findall(r"\d+(?:\.\d+)?", expression)
            valid = all(n in {"0", "1"} for n in numbers) and any(c.isalpha() for c in expression)
        else:
            valid = not bool(re.search(r"\d", expression))
        if not valid:
            raise ValueError("Numeric prose must be generated by an evidence placeholder")
        return ""

    text = re.sub(r"\$\$[\s\S]*?\$\$|\$[^$\n]*\$", mathematical, text)
    text = re.sub(r"\]\([^)]+\)", "]", text)
    text = re.sub(r"`[a-f0-9]{40}`", "", text)
    if re.search(r"\d|[%‰]", text):
        raise ValueError("Numeric prose must be generated by an evidence placeholder")
    if "{{" in text or "}}" in text:
        raise ValueError("Malformed evidence placeholder")
    abstract = source.split("## Abstract")[0]
    lines = [line for line in abstract.splitlines() if line and not line.startswith("#")]
    if len(lines) not in (5, 6):
        raise ValueError("Paper must start with five or six plain-English summary lines")


def render(source: str, research: Path) -> str:
    validate_source(source)
    manifest = json.loads((research / "manifest.json").read_text())
    if manifest["registration_commit"] != REGISTRATION:
        raise ValueError("Evidence registration mismatch")
    if manifest["hypotheses_sha256"] != digest(ROOT / "docs/hypotheses.md"):
        raise ValueError("Hypotheses hash mismatch")
    if manifest["config_sha256"] != digest(ROOT / "configs/ablations.yaml"):
        raise ValueError("Registered configuration changed; rerun research")
    for filename, expected in manifest["artifacts"].items():
        path = research / filename
        if not path.resolve().is_relative_to(research.resolve()):
            raise ValueError("Artifact path escapes research directory")
        if not path.is_file() or digest(path) != expected:
            raise ValueError(f"Missing or changed evidence artifact: {filename}")
    tables = {p.stem: json.loads(p.read_text()) for p in (research / "tables").glob("*.json")}

    def substitute(match: re.Match[str]) -> str:
        kind, name = match.groups()
        if kind == "fig":
            if f"figures/{name}.svg" not in manifest["artifacts"]:
                raise ValueError(f"Unknown figure: {name}")
            path = research.resolve() / "figures" / f"{name}.png"
            import os

            relative = os.path.relpath(path, ROOT / "docs")
            return f"![{name}; run status and actual n in companion table]({relative})"
        if name == "reported_checks":
            note = (ROOT / "docs/REAL_MODEL_RESULTS.md").read_text()
            section = note.split("## What I measured\n", 1)[1].split("## Notes and limits", 1)[0]
            if not section.strip().startswith("| Check | Result |"):
                raise ValueError("Reported results table is missing")
            return (
                section.strip()
                + "\n\nSource: [streamer-supplied results and limits](REAL_MODEL_RESULTS.md)."
            )
        if name == "registration":
            return (
                f"Registered before measurement: [{REGISTRATION}]"
                f"(https://github.com/manazafzal/codex-twitchcon-2026/commit/{REGISTRATION}).\n\n"
                f"Hypotheses SHA-256: `{manifest['hypotheses_sha256']}`.\n\n"
                f"Design: {manifest['config']['concepts']} concepts; {manifest['config']['prompts']} prompts; "
                f"seed {manifest['seed']}; {manifest['bootstrap_resamples']} concept-cluster resamples. "
                f"Model: {manifest['model']}. Source commit: `{manifest['git_hash']}`."
            )
        if name not in tables:
            raise ValueError(f"Unknown table: {name}")
        rows: list[dict[str, Any]] = tables[name]
        if name == "v4":
            rows = [
                r
                for r in rows
                if r.get("selected_by_validation")
                or (
                    r["layers"] == [16, 20, 22]
                    and r["whitening"] == "standardize"
                    and r["classifier"] == "lda"
                    and r["train_size"] == 66
                )
            ]
        if name == "alarm":
            rows = [r for r in rows if r["z"] == 4 and r["run"] == 8 and r["percentile"] == 99.5]
        return markdown(rows) + f"\n[Complete {name} table](../research/tables/{name}.csv)"

    return PLACEHOLDER.sub(substitute, source).rstrip() + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Render the registered NOUS research paper")
    parser.add_argument("--research", type=Path, default=ROOT / "research")
    parser.add_argument("--source", type=Path, default=ROOT / "docs/paper.src.md")
    parser.add_argument("--output", type=Path, default=ROOT / "docs/paper.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    rendered = render(args.source.read_text(), args.research)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != rendered:
            raise SystemExit("Paper is stale; run make paper and commit the regenerated paper")
    else:
        args.output.write_text(rendered)
    print(
        f"Paper {'verified' if args.check else 'rendered'}; SHA-256 "
        f"{hashlib.sha256(rendered.encode()).hexdigest()}"
    )


if __name__ == "__main__":
    main()
